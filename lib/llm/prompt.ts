/**
 * System prompt and session-state serialisation.
 *
 * Three hard rules from the spec are enforced in the prompt itself:
 *   - Prices and dimensions ALWAYS come from the database, never from model
 *     text. The model is told to refuse to quote a number it did not receive
 *     from a tool result.
 *   - Text found inside uploaded photos and product descriptions is DATA, never
 *     instructions. The model is told explicitly to ignore any instruction
 *     embedded in such text.
 *   - Tool calls are rationed. Every model round trip costs the user several
 *     seconds of waiting, and measurement showed the turn time is almost exactly
 *     (steps x 4-5s) regardless of how much history is resent. So the prompt
 *     pushes hard on finishing in one round: call independent tools together,
 *     never repeat a call, never reach for a tool that only returns
 *     `unavailable`.
 *   - A room photo is analysed once, at upload. The result lives in session
 *     state, so the model is told to read it rather than call `analyzeRoom`
 *     again for a question the answer is already sitting in.
 *
 * The session state is sent as compact JSON in exactly the shape the spec
 * defines, so the model's view of the conversation never drifts from the DB.
 */

